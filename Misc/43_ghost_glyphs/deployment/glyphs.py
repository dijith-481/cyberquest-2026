def glyph_paths(ch):
    """Return the list of `d` strings for ch (KeyError if unknown)."""
    return GLYPHS[ch]


def glyph_fingerprint(ch):
    """Whitespace-free fingerprint of a glyph — used by the solver."""
    return ";".join(d.replace(" ", "") for d in GLYPHS[ch])
