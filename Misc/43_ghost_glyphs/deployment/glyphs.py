def _ell(cx, cy, rx, ry):
    """Ellipse as two arcs (a full closed stroke)."""
    return (
        f"M{cx - rx:g},{cy:g} "
        f"A{rx:g},{ry:g} 0 0 1 {cx + rx:g},{cy:g} "
        f"A{rx:g},{ry:g} 0 0 1 {cx - rx:g},{cy:g}"
    )


def _circ(cx, cy, r):
    return _ell(cx, cy, r, r)


